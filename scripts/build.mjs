// Build: `npm run build -- --env dev|prod` (ADR-0005 Build). Writes dist/Code.js, dist/index.html,
// dist/appsscript.json and dist/.clasp.json. Fails on a scope outside docs/spec.md section 9 or a bundle over budget.
import { build } from "esbuild";
import { mkdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { checkBudget } from "./lib/budget.mjs";
import { parseEnv } from "./lib/deployConfig.mjs";
import { checkScopes } from "./lib/scopes.mjs";
import { generateStubs } from "./lib/stubs.mjs";
import {
  DIST,
  ROOT,
  fail,
  gitShortSha,
  loadDeployConfig,
  readJson,
  writeJson,
} from "./tools.mjs";
import { webPage } from "./web.mjs";

const GLOBAL_NAME = "App";
const SERVER_ENTRY = join(ROOT, "src", "entry.ts");
const COMMON = {
  bundle: true,
  target: "es2020",
  write: false,
  logLevel: "warning",
  charset: "utf8",
};

async function exportedNames(define) {
  const probe = await build({
    ...COMMON,
    entryPoints: [SERVER_ENTRY],
    format: "esm",
    metafile: true,
    outdir: DIST,
    define,
  });
  const [output] = Object.values(probe.metafile.outputs);
  return output.exports;
}

async function bundleServer(define, banner) {
  const result = await build({
    ...COMMON,
    entryPoints: [SERVER_ENTRY],
    format: "iife",
    globalName: GLOBAL_NAME,
    define,
  });
  const stubs = generateStubs(await exportedNames(define), GLOBAL_NAME);
  return `${banner}\n${result.outputFiles[0].text}\n${stubs}`;
}

function checkedManifest() {
  const manifest = readJson(join(ROOT, "appsscript.json"));
  const errors = checkScopes(
    manifest,
    readJson(join(ROOT, "scripts", "approved-scopes.json")),
  );
  if (errors.length > 0) fail(`Scope check failed:\n  ${errors.join("\n  ")}`);
  return manifest;
}

function reportSizes() {
  const sizes = Object.fromEntries(
    ["Code.js", "index.html"].map((name) => [
      name,
      statSync(join(DIST, name)).size,
    ]),
  );
  const { lines, errors } = checkBudget(sizes);
  for (const line of lines) console.log(`  ${line}`);
  if (errors.length > 0) fail(errors.join("\n"));
}

async function main() {
  const { values } = parseArgs({ options: { env: { type: "string" } } });
  const env = parseEnv(values.env);
  const config = loadDeployConfig(env);
  const sha = gitShortSha();
  const manifest = checkedManifest();
  const define = {
    __APP_ENV__: JSON.stringify(env),
    __EXEC_URL__: JSON.stringify(config.execUrl),
    __GIT_SHA__: JSON.stringify(sha),
  };
  const banner = `// Migway Templates ${env} ${sha}. Generated by scripts/build.mjs; edit src/, not this file.`;
  const code = await bundleServer(define, banner);
  const html = await webPage({ harness: false });
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(DIST, { recursive: true });
  writeFileSync(join(DIST, "Code.js"), code);
  writeFileSync(join(DIST, "index.html"), html);
  writeJson(join(DIST, "appsscript.json"), manifest);
  writeJson(join(DIST, ".clasp.json"), {
    scriptId: config.scriptId,
    rootDir: ".",
  });
  console.log(`Built ${env} ${sha} (mode ${config.mode}) into dist/`);
  reportSizes();
  if (config.execUrl === "")
    console.warn(
      `WARNING: deploy/${env}.json has no execUrl; the add-on cannot reach the server.`,
    );
}

main().catch((error) =>
  fail(error instanceof Error ? error.message : String(error)),
);
